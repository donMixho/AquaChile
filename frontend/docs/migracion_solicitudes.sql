-- Migración: solicitudes de cargo (requerimientos de contratación), antes datos mock.
-- Ejecutar una vez en Supabase > SQL Editor. Es idempotente.

CREATE TABLE IF NOT EXISTS public.solicitudes (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo        text NOT NULL,
  cargo         text NOT NULL,
  familia_cargo text NOT NULL,
  vacantes      integer NOT NULL DEFAULT 1 CHECK (vacantes > 0),
  estado        text NOT NULL DEFAULT 'Abierta' CHECK (estado IN ('Abierta', 'En proceso', 'Cerrada')),
  descripcion   text,
  created_at    timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.solicitudes ENABLE ROW LEVEL SECURITY;

-- Lectura para cualquier usuario autenticado; creación para sesiones autenticadas.
-- Ajusta estas políticas a los roles reales (ver docs/politicas_rls_candidatos.sql).
DROP POLICY IF EXISTS solicitudes_select ON public.solicitudes;
CREATE POLICY solicitudes_select ON public.solicitudes
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS solicitudes_insert ON public.solicitudes;
CREATE POLICY solicitudes_insert ON public.solicitudes
  FOR INSERT TO authenticated WITH CHECK (true);

