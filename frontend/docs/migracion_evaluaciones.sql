-- Entrevistas: apuntes y resultado de la entrevista de cada candidato.
-- Ejecutar en Supabase > SQL Editor DESPUÉS de docs/migracion_perfiles.sql. Es idempotente.
--
-- Una fila por candidato. Nace como 'borrador' mientras el reclutador entrevista (se guarda sola)
-- y pasa a 'finalizada' cuando decide Apto o No apto.

-- candidato_id copia el tipo real de candidatos.id (entero, bigint o uuid), para que la clave foránea
-- no falle si tu tabla no se creó exactamente como en docs/schema.sql.
DO $$
DECLARE
  tipo_candidato text;
BEGIN
  IF to_regclass('public.candidatos') IS NULL THEN
    RAISE EXCEPTION 'No existe la tabla public.candidatos. Ejecuta primero docs/schema.sql.';
  END IF;
  IF to_regclass('public.perfiles') IS NULL THEN
    RAISE EXCEPTION 'No existe la tabla public.perfiles. Ejecuta primero docs/migracion_perfiles.sql.';
  END IF;

  SELECT format_type(a.atttypid, a.atttypmod) INTO tipo_candidato
  FROM pg_attribute a
  WHERE a.attrelid = 'public.candidatos'::regclass AND a.attname = 'id' AND NOT a.attisdropped;

  EXECUTE format($f$
    CREATE TABLE IF NOT EXISTS public.evaluaciones (
      id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      candidato_id     %s NOT NULL UNIQUE REFERENCES public.candidatos (id) ON DELETE CASCADE,
      evaluador_id     uuid REFERENCES public.perfiles (id) ON DELETE SET NULL,
      enlace_reunion   text,
      respuestas       jsonb NOT NULL DEFAULT '{}'::jsonb,
      observaciones    text,
      resultado        text CHECK (resultado IN ('Apto', 'No apto')),
      estado           text NOT NULL DEFAULT 'borrador' CHECK (estado IN ('borrador', 'finalizada')),
      fecha_entrevista date,
      created_at       timestamptz NOT NULL DEFAULT now(),
      actualizado_en   timestamptz NOT NULL DEFAULT now()
    )$f$, tipo_candidato);
END
$$;

-- Modalidad de la entrevista: por videollamada (enlace_reunion) o presencial (lugar).
-- fecha_hora queda lista para la futura agenda; hoy no se usa. Idempotente: sirve si la tabla ya existía.
ALTER TABLE public.evaluaciones
  ADD COLUMN IF NOT EXISTS modalidad  text NOT NULL DEFAULT 'Videollamada' CHECK (modalidad IN ('Videollamada', 'Presencial')),
  ADD COLUMN IF NOT EXISTS lugar      text,
  ADD COLUMN IF NOT EXISTS fecha_hora timestamptz;

ALTER TABLE public.evaluaciones ENABLE ROW LEVEL SECURITY;

-- Lectura: admin y reclutador ven todas. Operaciones solo las de candidatos que ya son Apto, para
-- que no vea apuntes de personas descartadas o aún en evaluación.
DROP POLICY IF EXISTS "evaluaciones_select" ON public.evaluaciones;
CREATE POLICY "evaluaciones_select"
  ON public.evaluaciones FOR SELECT TO authenticated
  USING (
    public.usuario_activo() AND (
      (auth.jwt() -> 'app_metadata' ->> 'rol') IN ('admin', 'reclutador')
      OR (
        (auth.jwt() -> 'app_metadata' ->> 'rol') = 'operaciones'
        AND EXISTS (SELECT 1 FROM public.candidatos c WHERE c.id = candidato_id AND c.estado = 'Apto')
      )
    )
  );

-- Escritura: solo admin y reclutador activos. No hay política de DELETE: las entrevistas no se borran
-- (se eliminan en cascada solo si se elimina al candidato).
DROP POLICY IF EXISTS "evaluaciones_insert" ON public.evaluaciones;
CREATE POLICY "evaluaciones_insert"
  ON public.evaluaciones FOR INSERT TO authenticated
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'rol') IN ('admin', 'reclutador') AND public.usuario_activo());

DROP POLICY IF EXISTS "evaluaciones_update" ON public.evaluaciones;
CREATE POLICY "evaluaciones_update"
  ON public.evaluaciones FOR UPDATE TO authenticated
  USING ((auth.jwt() -> 'app_metadata' ->> 'rol') IN ('admin', 'reclutador') AND public.usuario_activo())
  WITH CHECK ((auth.jwt() -> 'app_metadata' ->> 'rol') IN ('admin', 'reclutador') AND public.usuario_activo());

-- Refresca la caché del API para que la tabla nueva se vea al instante.
NOTIFY pgrst, 'reload schema';

